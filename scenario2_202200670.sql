CREATE OR REPLACE PROCEDURE lab_res_lab.show_low_availability_sessions()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT session_name, available_workstations
        FROM lab_res_lab.lab_sessions
        WHERE available_workstations <= 2
        ORDER BY session_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low availability: % (% remaining)', v_item.session_name, v_item.available_workstations;
    END LOOP;
    CLOSE c_low;
END;
$$;

